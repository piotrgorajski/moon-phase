# =========================================================
# USTAWIENIA FONTU
# =========================================================

SCALE = 2

CHAR_WIDTH = 5 * SCALE
CHAR_HEIGHT = 7 * SCALE

CHAR_SPACING = 2


# =========================================================
# SZEROKOSC TEKSTU
# =========================================================

def text_width(text):

    if len(text) == 0:
        return 0

    return (
        len(text) * CHAR_WIDTH
        + (len(text) - 1) * CHAR_SPACING
    )


# =========================================================
# RYSOWANIE TEKSTU
# =========================================================

def draw_text(LCD, text, x, y, color):

    for char in text:

        glyph = FONT.get(char)

        if glyph is None:
            # Nieznany znak traktujemy jak spację.
            glyph = FONT[" "]

        for row in range(7):

            line = glyph[row]

            for col in range(5):

                if line[col] == "1":

                    # Powiększenie 2x
                    LCD.fill_rect(
                        x + col * SCALE,
                        y + row * SCALE,
                        SCALE,
                        SCALE,
                        color
                    )

        x += CHAR_WIDTH + CHAR_SPACING


# =========================================================
# TEKST WYŚRODKOWANY
# =========================================================

def draw_centered(LCD, text, y, color):

    width = text_width(text)

    x = (LCD.width - width) // 2

    draw_text(
        LCD,
        text,
        x,
        y,
        color
    )